import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { mkdir } from "node:fs/promises";
const directory = "../artifacts/metadata-recovery";

test("administrator recovery, persistent jobs and data-source forms use local APIs", async ({ page }) => {
  await mkdir(directory, { recursive: true });
  const errors: string[] = [], external: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (/everloot\.app|foreverdb\.net|thewowdb\.com/.test(request.url())) external.push(request.url()); });
  await page.goto("/");
  await page.getByLabel("Username", { exact: true }).fill("owner");
  await page.getByLabel("Password", { exact: true }).fill("synthetic browser owner password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Market Explorer", exact: true })).toBeVisible();
  const initialSession=await (await page.request.get("/api/v1/auth/session")).json();
  const existing=await (await page.request.get("/api/v1/admin/item-metadata/jobs")).json();
  for(const job of existing.jobs) if(["queued","running","paused"].includes(job.state)) await page.request.post(`/api/v1/admin/item-metadata/jobs/${job.id}/cancel`,{headers:{"X-CSRF-Token":initialSession.csrf_token}});
  await page.getByRole("button", { name: "Administration", exact: true }).click();
  await page.getByRole("link", { name: "Item Metadata", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Item Metadata", exact: true })).toBeVisible();
  await expect(page.getByRole("heading",{name:"Coverage in the selected market",exact:true})).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/01-overview.png`, fullPage: true });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
  await page.getByRole("button",{name:"Recovery jobs",exact:true}).click();
  await page.getByLabel("Numeric item ID").fill("20002");
  await page.getByRole("button", { name: "Preview recovery", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Recovery preview" })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/02-single-item.png`, fullPage: true });
  await page.getByRole("button", { name: "Start recovery", exact: true }).click();
  await expect(page.getByText(/Recovery job #\d+ queued/)).toBeVisible();
  const queuedText=await page.getByText(/Recovery job #\d+ queued/).textContent();
  const queuedId=queuedText!.match(/#(\d+)/)![1];
  const active=page.getByRole("table",{name:"recovery jobs",exact:true}).getByRole("row").filter({has:page.getByRole("button",{name:`Job #${queuedId} · single`,exact:true})});
  await active.getByRole("button", { name: "Pause", exact: true }).click();
  await expect(active.getByRole("button", { name: "Resume", exact: true })).toBeVisible();
  await active.getByRole("button", { name: "Resume", exact: true }).click();
  await active.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(page.getByLabel("Recovery progress")).toBeVisible();
  const complete = page.getByRole("table",{name:"recovery jobs",exact:true}).getByRole("row").filter({ hasText: "completed" }).last();
  await complete.getByRole("button", { name: /Job #/ }).click();
  await expect(page.getByRole("table", { name: "job results", exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/04-progress-results.png`, fullPage: true });
  await page.getByLabel("Recovery action").selectOption("missing");
  await page.getByRole("button", { name: "Preview recovery", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Recovery preview" })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/03-batch-preview.png`, fullPage: true });
  await page.getByRole("link", { name: "Data Sources", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Data Sources", exact: true })).toBeVisible();
  await page.getByText("Provider evidence",{exact:true}).click();
  await expect(page.getByRole("table",{name:"provider health"}).getByText("Access forbidden",{exact:true})).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/05-data-sources.png`, fullPage: true });
  await expect(page.getByText("Edit settings",{exact:true})).toHaveCount(4);
  const everloot = page.getByRole("region", { name: "Everloot connection", exact: true });
  await everloot.getByText("Edit settings",{exact:true}).click();
  await everloot.getByRole("button", { name: "Add API Key", exact: true }).click();
  await expect(page.getByLabel("New API key", { exact: true })).toBeVisible();
  // Capture an empty secret form only. No screenshots/traces contain credential values.
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/06-key-replacement.png`, fullPage: true });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
  await page.getByLabel("New API key", { exact: true }).fill("evl_fake_browser_test_only");
  await page.getByRole("button", { name: "Validate & replace", exact: true }).click();
  await expect(page.getByText(/Replacement queued for validation/)).toBeVisible();
  await expect(page.getByLabel("New API key", { exact: true })).toHaveCount(0);
  const session = await (await page.request.get("/api/v1/auth/session")).json();
  expect((await page.request.post("/api/v1/admin/metadata-providers/everloot/credentials", { data: { key: "evl_fake_browser_test_only" } })).status()).toBe(403);
  const state = await (await page.request.get("/api/v1/admin/metadata-providers")).text();
  expect(state).not.toContain("evl_fake_browser_test_only");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/09-mobile-sources.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "Market Explorer", exact: true }).click();
  await page.getByLabel("Search items", { exact: true }).fill("Recovered Gloves");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await expect(page.getByText("Synthetic Recovered Gloves", { exact: true }).first()).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/07-explorer.png`, fullPage: true });
  await page.getByRole("button", { name: /Synthetic Recovered Gloves/ }).first().click();
  await page.getByRole("dialog").getByText("Technical details",{exact:true}).click();
  await expect(page.getByRole("dialog").getByText("Field provenance", { exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${directory}/08-tooltip-provenance.png`, fullPage: true });
  expect(external).toEqual([]); expect(errors).toEqual([]);
  // Keep the normal account-bound CSRF contract exercised without exposing its value.
  expect(typeof session.csrf_token).toBe("string");
});
