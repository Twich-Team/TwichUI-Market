import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { mkdir, writeFile } from "node:fs/promises";
const output="../artifacts/provider-rates";
test.use({timezoneId:"America/Denver"});

test("provider rate limits: editable allowances, quota observations, cooldowns and waiting jobs",async({page})=>{
  test.setTimeout(60000);
  await mkdir(output,{recursive:true});
  const errors:string[]=[],external:string[]=[];
  page.on("pageerror",error=>errors.push(error.message));
  page.on("request",request=>{if(/everloot\.app|foreverdb\.net|thewowdb\.com/.test(request.url()))external.push(request.url());});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto("/");
  await page.getByLabel("Username",{exact:true}).fill("owner");
  await page.getByLabel("Password",{exact:true}).fill("synthetic browser owner password");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Market Explorer",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Administration",exact:true}).click();
  await page.getByRole("tab",{name:"Data Sources",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Data Sources",exact:true})).toBeVisible();
  await page.screenshot({path:`${output}/01-data-sources.png`,fullPage:true});
  const forever=page.getByRole("region",{name:"ForeverDB connection",exact:true});
  const ever=page.getByRole("region",{name:"Everloot connection",exact:true});
  const wow=page.getByRole("region",{name:"TheWoWDB connection",exact:true});
  await expect(forever.getByLabel("Requests per minute",{exact:true})).toHaveValue("60");
  await forever.screenshot({path:`${output}/02-foreverdb-limits.png`});
  await expect(ever.getByLabel("Hourly budget",{exact:true})).toHaveValue("2000");
  await ever.screenshot({path:`${output}/03-everloot-limits.png`});
  await expect(wow.getByLabel("Sustained requests per second",{exact:true})).toHaveValue("2");
  await expect(wow.getByLabel("Short burst allowance",{exact:true})).toHaveValue("120");
  await wow.screenshot({path:`${output}/04-thewowdb-token-bucket.png`});
  await expect(ever).toContainText("Provider-reported observation: 1,650 remaining of 2,000");
  await ever.locator(".provider-usage").screenshot({path:`${output}/06-provider-reported-quota.png`});
  await expect(forever).toContainText("application estimate");
  await expect(forever).toContainText("Rate limit cooldown");
  await forever.locator(".provider-usage").screenshot({path:`${output}/07-application-estimated-quota.png`});
  await forever.getByLabel("Requests per minute",{exact:true}).fill("120");
  await forever.getByLabel("Daily budget",{exact:true}).fill("20000");
  await expect(forever.getByRole("button",{name:"Save rate limits",exact:true})).toBeDisabled();
  await forever.getByLabel(/I confirm that my provider contract/).check();
  await forever.screenshot({path:`${output}/05-edit-custom-allowance.png`});
  const before=(await (await page.request.get("/api/v1/admin/metadata-providers")).json()).providers.find((p:{provider:string})=>p.provider==="foreverdb");
  await forever.getByRole("button",{name:"Save rate limits",exact:true}).click();
  await expect(page.getByText("ForeverDB rate limits saved. Usage and cooldowns are preserved.",{exact:true})).toBeVisible();
  const after=(await (await page.request.get("/api/v1/admin/metadata-providers")).json()).providers.find((p:{provider:string})=>p.provider==="foreverdb");
  expect(after.hour_used).toBe(before.hour_used);expect(after.day_used).toBe(before.day_used);
  expect(after.cooldown_until).toBe(before.cooldown_until);expect(after.enabled).toBe(before.enabled);expect(after.automatic).toBe(before.automatic);
  await page.reload();
  await page.getByRole("tab",{name:"Data Sources",exact:true}).click();
  await expect(page.getByLabel("Requests per minute",{exact:true})).toHaveValue("120");
  await forever.locator(".provider-usage").screenshot({path:`${output}/08-http-429-cooldown.png`});
  const session=await (await page.request.get("/api/v1/auth/session")).json();
  const invalid=await page.request.patch("/api/v1/admin/metadata-providers/foreverdb/rate-limits",{headers:{"X-CSRF-Token":session.csrf_token},data:{...after.rate_limits.configured,minimum_interval:0}});
  expect(invalid.status()).toBe(422);
  await page.getByRole("tab",{name:"Item Metadata",exact:true}).click();
  await expect(page.getByText(/Waiting for ForeverDB rate limit — resumes at/).first()).toBeVisible();
  await page.getByRole("heading",{name:"Recovery jobs",exact:true}).locator("..").screenshot({path:`${output}/09-recovery-waiting-for-quota.png`});
  await page.getByRole("tab",{name:"Data Sources",exact:true}).click();
  const desktopAxe=await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa"]).analyze();expect(desktopAxe.violations).toEqual([]);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:`${output}/10-mobile-administration.png`,fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const presetBounds=await forever.getByLabel("Documented allowance preset",{exact:true}).boundingBox();
  const formBounds=await forever.getByRole("region",{name:"ForeverDB rate limits",exact:true}).boundingBox();
  expect(presetBounds!.x+presetBounds!.width).toBeLessThanOrEqual(formBounds!.x+formBounds!.width+1);
  const mobileAxe=await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa"]).analyze();expect(mobileAxe.violations).toEqual([]);
  // Keyboard opens advanced limits; ordinary polling must preserve unsaved edits.
  await forever.getByText("Advanced limits",{exact:true}).focus();await page.keyboard.press("Enter");
  await expect(forever.getByLabel("Minimum interval (seconds)",{exact:true})).toBeVisible();
  await forever.getByLabel("Requests per minute",{exact:true}).fill("121");
  await page.waitForResponse(response=>response.url().endsWith("/api/v1/admin/metadata-providers")&&response.request().method()==="GET");
  await expect(forever.getByLabel("Requests per minute",{exact:true})).toHaveValue("121");
  await ever.getByRole("button",{name:"Replace API Key",exact:true}).click();
  await expect(ever.getByLabel("New API key",{exact:true})).toBeVisible();
  await ever.getByRole("button",{name:"Cancel",exact:true}).click();
  expect(errors).toEqual([]);expect(external).toEqual([]);
  await writeFile(`${output}/verification.json`,JSON.stringify({origin:"synthetic",provider_requests:0,desktop_axe_violations:desktopAxe.violations.length,mobile_axe_violations:mobileAxe.violations.length,screenshots:10,saved_configuration:true,usage_and_cooldown_preserved:true,provider_enablement_preserved:true},null,2));
});
